package com.self.springbootprojectstarter.config;

import com.self.springbootprojectstarter.DTO.CategoryDto;
import com.self.springbootprojectstarter.DTO.OrderDto;
import com.self.springbootprojectstarter.DTO.ProductDto;
import com.self.springbootprojectstarter.DTO.ProfileDto;
import com.self.springbootprojectstarter.DTO.UserDto;
import com.self.springbootprojectstarter.model.Category;
import com.self.springbootprojectstarter.model.Order;
import com.self.springbootprojectstarter.model.Product;
import com.self.springbootprojectstarter.model.Profile;
import com.self.springbootprojectstarter.model.User;
import org.modelmapper.ModelMapper;
import org.modelmapper.convention.MatchingStrategies;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * 🔹 MapperConfig
 *
 * Teaching points:
 * 1️⃣ Central place to configure ModelMapper, which maps between DTOs and Entities.
 * 2️⃣ Ensures all services/mappers use the same rules.
 * 3️⃣ Avoids clients accidentally overwriting database IDs or mapping nulls incorrectly.
 */
@Configuration
public class MapperConfig {

    @Bean
    // Exposes a shared ModelMapper bean to be injected anywhere (@Autowired or constructor)
    public ModelMapper modelMapper() {

        ModelMapper modelMapper = new ModelMapper();

        // ------------------- STRICT MATCHING -------------------
        // Teaching point:
        // STRICT matching ensures fields only map if names & types match exactly.
        // Prevents accidental mapping of wrong fields (e.g., firstName → lastName)
        modelMapper.getConfiguration()
                .setMatchingStrategy(MatchingStrategies.STRICT)
                .setSkipNullEnabled(true); // Do not overwrite existing entity fields with null values from DTO

        // ------------------- IGNORE CLIENT-SUPPLIED IDs -------------------
        // Teaching point:
        // When clients send DTOs for creation or update, they may send an id.
        // We NEVER want to overwrite DB-generated ids when mapping from DTO → Entity.
        modelMapper.typeMap(UserDto.class, User.class)
                .addMappings(mapper -> mapper.skip(User::setId));
        modelMapper.typeMap(ProfileDto.class, Profile.class)
                .addMappings(mapper -> mapper.skip(Profile::setId));
        modelMapper.typeMap(CategoryDto.class, Category.class)
                .addMappings(mapper -> mapper.skip(Category::setId));
        modelMapper.typeMap(ProductDto.class, Product.class)
                .addMappings(mapper -> mapper.skip(Product::setId));
        modelMapper.typeMap(OrderDto.class, Order.class)
                .addMappings(mapper -> mapper.skip(Order::setId));

        // 💡 Key points:
        // - We set skip for all entities because IDs are auto-generated by the database.
        // - Prevents accidental changes if client tries to manipulate ids.
        // - Combined with skipNullEnabled=true, we ensure safe partial updates.

        return modelMapper; // Return configured ModelMapper for injection
    }
}